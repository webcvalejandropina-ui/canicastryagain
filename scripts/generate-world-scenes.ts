/** Offline foreground generation. Run with npm run assets:worlds, never on a request. */
import { createHash } from "node:crypto";
import { mkdir, writeFile } from "node:fs/promises";
import { resolve, join } from "node:path";
import { WORLDS, type WorldId } from "../src/features/appearance/worlds";
import sceneries from "../src/features/appearance/sceneryAssets.json";
import illustrations from "../src/features/appearance/illustrationAssets.json";

type AssetPair = {far: string; farSmall: string; near: string};
const directory = resolve("public/worlds");

function foreground(id: WorldId, theme: "light" | "dark") {
  const [, , , , grass, soil, , rock] = WORLDS[id][theme];
  const snow = id === "christmas", coast = id === "summer" || id === "none";
  const terrain = snow ? (theme === "dark" ? "#8eaeb1" : "#e3eeea") : grass;
  let shapes = `<defs><linearGradient id="stone" x2=".7" y2="1"><stop stop-color="${snow ? terrain : rock}"/><stop offset="1" stop-color="${soil}"/></linearGradient><linearGradient id="blade" x2="0" y2="1"><stop stop-color="${terrain}" stop-opacity=".7"/><stop offset="1" stop-color="${soil}"/></linearGradient></defs>`;
  shapes += `<path d="M315 886q48-19 93 0l-8 35h-90Zm474 5q43-24 100-8v38H786Z" fill="url(#stone)" opacity=".75"/>`;
  for (let i = 0; i < 20; i++) {
    const x = i < 10 ? 330 + i * 9 : 795 + (i - 10) * 9;
    const base = 904 + i % 4 * 3, height = 25 + i * 17 % 66;
    shapes += snow || coast
      ? `<path d="m${x} ${base} 6-${height / 3} 23-9 19 14 5 30Z" fill="url(#stone)" opacity="${.2 + i % 4 * .1}"/>`
      : `<path d="M${x} ${base}q-2-${height * .7} -${12 + i % 8}-${height}q20 17 18 ${height}m-4 0q2-${height * .5} 16-${height * .7}q-5 26-12 ${height * .7}" fill="url(#blade)" opacity="${.3 + i % 4 * .12}"/>`;
  }
  if (id === "birthday") shapes += `<g transform="translate(823 845)" opacity=".72"><path d="M0-12q9 30-2 50m-13-62q0 35 12 62" stroke="#d5ab83" fill="none"/><ellipse cy="-20" rx="10" ry="14" fill="#d7b8bb"/><ellipse cx="-15" cy="-32" rx="9" ry="13" fill="#ebd7b8"/></g>`;
  if (id === "birthday") {
    shapes += `<path d="M290 112q310 105 620 0" fill="none" stroke="#e7cdae" stroke-width="2" opacity=".7"/>`;
    for(let i=0;i<7;i++) {const x=360+i*80;const y=138+Math.sin(i/6*Math.PI)*25;shapes+=`<path d="m${x} ${y} 20 2-12 24Z" fill="${['#dfadad','#e9ce92','#99b6ac'][i%3]}" opacity=".75"/>`;}
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 900" preserveAspectRatio="xMidYMax slice">${shapes}</svg>`;
}

async function generate() {
  await mkdir(directory, { recursive: true });
  const manifest = {} as Record<WorldId, Record<"light" | "dark", AssetPair>>;
  for (const id of Object.keys(WORLDS) as WorldId[]) {
    manifest[id] = {} as Record<"light" | "dark", AssetPair>;
    const illustration = id==="none"?sceneries.gibraltar:id==="summer"?sceneries.tarifa:(illustrations as Partial<Record<WorldId, {small: string; large: string}>>)[id] ?? illustrations.none;
    for (const theme of ["light", "dark"] as const) {
      const svg = foreground(id, theme);
      const hash = createHash("sha256").update(svg).digest("hex").slice(0, 10);
      const filename = `${id}-${theme}-near.${hash}.svg`;
      await writeFile(join(directory, filename), svg);
      manifest[id][theme] = { far: illustration.large, farSmall: illustration.small, near: `/worlds/${filename}` };
      console.log(`${filename}: ${Buffer.byteLength(svg)} B`);
    }
  }
  await writeFile(resolve("src/features/appearance/sceneAssets.ts"),
    `// Generated by npm run assets:worlds. Content hashes keep browser caching safe.\nexport const SCENE_ASSETS = ${JSON.stringify(manifest, null, 2)} as const;\n`);
}
void generate().catch(error => { console.error(error); process.exitCode = 1; });
