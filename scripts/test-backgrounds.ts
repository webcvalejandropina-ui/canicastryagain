import assert from 'node:assert/strict';
import Database from 'better-sqlite3';
import { BackgroundStore, imageDimensions } from '../src/backend/appearance/BackgroundStore';
import { resolveManagedScene, type ManagedEvent } from '../src/features/appearance/events/calendar';
import { seasonalWeather } from '../src/features/appearance/events/backgrounds';
const db=new Database(':memory:');db.exec("CREATE TABLE players(id TEXT PRIMARY KEY,is_admin INTEGER);INSERT INTO players VALUES('admin',1),('user',0)");
const store=new BackgroundStore(db);
const png=Buffer.alloc(32);Buffer.from('89504e470d0a1a0a','hex').copy(png);png.write('IHDR',12);png.writeUInt32BE(1280,16);png.writeUInt32BE(720,20);
assert.deepEqual(imageDimensions(png),{width:1280,height:720,type:'image/png'});
assert.throws(()=>imageDimensions(Buffer.from('<svg onload="alert(1)">')));
assert.throws(()=>store.upload('user','Foto',png));
const asset=store.upload('admin','Mi pradera',png);assert.equal(store.list().length,1);assert.equal(store.read(asset.id)?.body.length,png.length);
assert.equal(store.upload('admin','Duplicado',png).id,asset.id);assert.equal(store.list().length,1);
assert.throws(()=>store.setDefault('user',{world:'none',backgroundId:asset.id}));
store.setDefault('admin',{world:'summer',backgroundId:asset.id});assert.equal(store.defaultBackground()?.backgroundId,asset.id);
assert.throws(()=>store.setDefault('admin',{world:'none',backgroundId:'a'.repeat(64)}));
const event:ManagedEvent={id:'winter',title:'Invierno',world:'christmas',effect:'none',area:'',enabled:true,recurrence:'always',start:'',end:'',priority:1,source:'',backgroundId:asset.id};
const date=new Date('2026-01-15T12:00:00Z');
assert.equal(resolveManagedScene({season:'auto',backgroundPolicy:'original'},[event],event,date,{world:'summer'}).world,'none');
assert.equal(resolveManagedScene({season:'auto',backgroundPolicy:'calendar'},[event],{...event,world:'birthday'},date,{world:'summer'}).world,'christmas');
assert.equal(resolveManagedScene({season:'auto'},[event],null,date,{world:'summer'}).world,'summer');
assert.equal(resolveManagedScene({season:'auto'},[event],{...event,world:'birthday'},date,{world:'summer'}).world,'birthday');
assert.equal(resolveManagedScene({season:'none'},[event],event,date,{world:'summer'}).backgroundId,undefined);
assert.equal(seasonalWeather(date),'rain');assert.equal(seasonalWeather(new Date('2026-07-10')),'fireflies');
assert.equal(resolveManagedScene({season:'auto'},[event],null,date,{world:'inherit',backgroundId:asset.id}).world,'christmas');
assert.equal(resolveManagedScene({season:'auto'},[event],null,date,{world:'inherit',backgroundId:asset.id}).backgroundId,asset.id);
db.close();
console.log('Backgrounds: upload limits, permissions, immutable IDs, player choice and seasonal weather OK');
