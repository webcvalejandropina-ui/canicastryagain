import assert from 'node:assert/strict';
import Database from 'better-sqlite3';
import { activeOn, selectEvent, resolveManagedScene, type ManagedEvent } from '../src/features/appearance/events/calendar';
import { AppearanceStore, eventSchema } from '../src/backend/appearance/AppearanceStore';
const event: ManagedEvent = {id:'test',title:'Fiesta',world:'birthday',effect:'confetti',enabled:true,area:'Pamplona',recurrence:'annual',start:'12-20',end:'01-06',priority:10,source:''};
assert(activeOn(event,new Date('2026-12-31T23:30:00Z')));
assert(!activeOn(event,new Date('2026-07-07T12:00:00Z')));
assert.equal(selectEvent([event],'Sevilla',new Date('2026-12-25')),null);
assert.equal(selectEvent([event],'PAMPLÓNA',new Date('2026-12-25'))?.id,'test');
assert(!eventSchema.safeParse({...event,start:'02-30'}).success);
assert(!eventSchema.safeParse({...event,recurrence:'once',start:'2027-02-29',end:'2027-03-01'}).success);
assert(!eventSchema.safeParse({...event,recurrence:'once',start:'2026-12-25',end:'2026-01-01'}).success);
assert.equal(resolveManagedScene({season:'none'},[event],event,new Date('2026-12-25')).world,'none');
assert.equal(resolveManagedScene({season:'auto'},[],{...event,world:'summer'},new Date('2026-12-25')).world,'summer');
assert.equal(resolveManagedScene({season:'auto',birthday:{month:12,day:25}},[],{...event,world:'summer'},new Date('2026-12-24T23:30:00Z'),null,{registered:true,birthday:{month:12,day:25}}).world,'birthday');
assert.equal(resolveManagedScene({season:'auto'},[{...event,enabled:false,area:''}],null,new Date('2026-12-25')).world,'none');
assert.equal(selectEvent([{...event,area:'',priority:1},{...event,id:'local',priority:40}],'Pamplona',new Date('2026-12-25'))?.id,'local');
const db = new Database(':memory:');
db.pragma('foreign_keys = ON');
db.exec('CREATE TABLE players(id TEXT PRIMARY KEY, is_admin INTEGER); INSERT INTO players VALUES (\'admin\',1),(\'user\',0)');
const store = new AppearanceStore(db);
assert.throws(()=>store.saveEvent('user',event));
store.saveEvent('admin',event);
assert.equal(store.events().find(e=>e.id==='test')?.title,'Fiesta');
store.assign('admin','user',event);
assert.equal(store.personal('user')?.title,'Fiesta');
store.assign('admin','user',null);
assert.equal(store.personal('user'),null);
assert.throws(()=>store.assign('admin','unknown',event));
assert.throws(()=>store.saveEvent("admin' OR 1=1--",event));
new AppearanceStore(db);
assert.equal(store.events().filter(e=>e.id==='test').length,1);
db.prepare('DELETE FROM players WHERE id=?').run('user');
assert.equal(store.personal('user'),null);
console.log('Managed events: dates, locality, authorization, persistence and assignments OK');
