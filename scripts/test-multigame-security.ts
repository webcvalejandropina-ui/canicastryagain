import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
process.env.SQLITE_PATH=':memory:';
async function run(){
 const {sqlite}=await import('../src/backend/shared/infrastructure/db/sqlite');
 const {POST:create,GET:list}=await import('../src/app/api/games/route');
 const {POST:join}=await import('../src/app/api/games/join/route');
 const {GET:get}=await import('../src/app/api/games/[gameId]/route');
 const {POST:move}=await import('../src/app/api/games/[gameId]/move/route');
 const {GET:adminList}=await import('../src/app/api/admin/users/route');
 const {POST:reset}=await import('../src/app/api/admin/users/reset-password/route');
 const {POST:bootstrap}=await import('../src/app/api/invitations/session/route');
 const {POST:login}=await import('../src/app/api/auth/login/route');
 const {hashPassword,verifyPassword}=await import('../src/backend/player/domain/PasswordHasher');
 const {limitAction,readSmallJson}=await import('../src/backend/shared/infrastructure/requestSecurity');
 const cookies:Record<string,string>={};
 for(const [i,id] of ['a','b','c','admin'].entries()){
  const token=String(i+1).repeat(64);cookies[id]=`canicas_session=${token}`;
  sqlite.prepare('INSERT INTO players(id,alias,password_hash,is_admin) VALUES(?,?,?,?)').run(id,id,await hashPassword('secret123'),id==='admin'?1:0);
  sqlite.prepare('INSERT INTO appearance_sessions(token_hash,player_id,expires) VALUES(?,?,?)').run(createHash('sha256').update(token).digest('hex'),id,Date.now()+60000);
 }
 const req=(path:string,body?:unknown,actor?:string,origin='http://localhost')=>new Request('http://localhost'+path,{method:body?'POST':'GET',headers:{origin,'content-type':'application/json',cookie:actor?cookies[actor]:''},...(body?{body:JSON.stringify(body)}:{})});
 const body=(id='a')=>({playerId:id,playerName:id,numRows:3});
 assert.equal((await create(req('/api/games',body()))).status,403);
 assert.equal((await create(req('/api/games',body('a'),'b'))).status,403);
 assert.equal((await create(req('/api/games',body(),'a','https://evil.example'))).status,403);
 const responses=await Promise.all(Array.from({length:6},()=>create(req('/api/games',body(),'a'))));
 assert.equal(responses.filter(r=>r.status===201).length,5);
 const denied=responses.find(r=>r.status!==201)!;assert.equal(denied.status,409);assert.equal((await denied.json()).code,'ACTIVE_GAME_LIMIT');
 const games=await Promise.all(responses.filter(r=>r.status===201).map(async r=>(await r.json()).game));
 const listed=await (await list(req('/api/games',undefined,'a'))).json();assert.equal(listed.games.length,5);
 assert.equal((await (await list(req('/api/games',undefined,'b'))).json()).games.length,0);
 assert.equal((await list(req('/api/games?playerId=a'))).status,403);
 const first=games[0],context={params:Promise.resolve({gameId:first.gameId})};
 assert.equal((await get(req(`/api/games/${first.gameId}?playerId=a`,undefined,'b'),context)).status,403);
 assert.equal((await move(req(`/api/games/${first.gameId}/move`,{playerId:'a',rowIndex:0,startIndex:0,removeCount:1},'b'),context)).status,403);
 assert.equal((await get(req(`/api/games/${first.gameId}?playerId=a`,undefined,'a'),context)).status,200);
 const other=(await (await create(req('/api/games',body('b'),'b'))).json()).game;
 assert.equal((await join(req('/api/games/join',{playerId:'a',playerName:'a',gameCode:other.gameCode},'a'))).status,409,'Joining must enforce the same cap');
 assert.equal((await join(req('/api/games/join',{playerId:'b',playerName:'b',gameCode:first.gameCode},'b'))).status,200);
 assert.equal((await join(req('/api/games/join',{playerId:'c',playerName:'a',gameCode:first.gameCode},'c'))).status,409,'Matching a name must never steal a seat');
 assert.equal((await join(req('/api/games/join',{playerId:'a',playerName:'a',gameCode:first.gameCode},'a'))).status,200,'Resuming at cap is allowed');
 sqlite.prepare("UPDATE games SET updated_at=? WHERE id=?").run(new Date(Date.now()-86400000).toISOString(),first.gameId);
 assert.equal((await create(req('/api/games',body(),'a'))).status,201,'Expired playing games release their slot');
 sqlite.prepare("UPDATE games SET status='finished' WHERE player1_id='a'").run();
 const privateGame=(await (await create(req('/api/games',{...body(),privateInvitation:true},'a'))).json()).game;
 const guestResponse=await bootstrap(req('/api/invitations/session',{gameCode:privateGame.gameCode}));assert.equal(guestResponse.status,200);
 const guest=(await guestResponse.json()).actor;
 const guestJoin=new Request('http://localhost/api/games/join',{method:'POST',headers:{origin:'http://localhost',cookie:guestResponse.headers.get('set-cookie')!.split(';')[0]},body:JSON.stringify({playerId:guest.playerId,playerName:guest.playerName,gameCode:privateGame.gameCode})});
 assert.equal((await join(guestJoin)).status,200,'A private invitation can also be entered by code');
 assert.equal((await adminList(req('/api/admin/users?adminId=admin',undefined,'a'))).status,403);
 assert.equal((await adminList(req('/api/admin/users?adminId=admin'))).status,401);
 assert.equal((await reset(req('/api/admin/users/reset-password',{adminId:'admin',targetId:'b'},'a'))).status,403);
 const resetResponse=await reset(req('/api/admin/users/reset-password',{adminId:'a',targetId:'b'},'admin'));assert.equal(resetResponse.status,200);
 const temporary=(await resetResponse.json()).temporaryPassword;assert.ok(temporary.length>=24);
 const stored=(sqlite.prepare('SELECT password_hash FROM players WHERE id=?').get('b')as{password_hash:string}).password_hash;
 assert.ok(await verifyPassword(temporary,stored));assert.equal(await verifyPassword('secret123',stored),false);
 assert.equal((await login(req('/api/auth/login',{alias:'b',password:'hijack-password'}))).status,401);
 sqlite.prepare("UPDATE players SET password_reset=1 WHERE id='b'").run();
 assert.equal((await login(req('/api/auth/login',{alias:'b',password:'hijack-password'}))).status,401,'Legacy reset flag cannot authorize a new password');
 process.env.ADMIN_ALIAS='reserved-admin';
 const aliasResponse=await login(req('/api/auth/login',{alias:'reserved-admin',password:'safeTest123'}));
 assert.equal(aliasResponse.status,200);assert.equal((await aliasResponse.json()).isAdmin,false,'A configured display alias does not grant administrator privileges');
 delete process.env.ADMIN_ALIAS;

 assert.equal((await create(req('/api/games',{...body(),padding:'x'.repeat(17000)},'a'))).status,413);
 const chunked=new Request('http://localhost',{method:'POST',body:new ReadableStream({start(c){c.enqueue(new Uint8Array(17000));c.close();}}),duplex:'half'} as RequestInit);
 await assert.rejects(readSmallJson(chunked),{code:'PAYLOAD_TOO_LARGE'});
 assert.equal((await create(new Request('http://localhost/api/games',{method:'POST',headers:{cookie:cookies.a},body:'{bad'}))).status,400);
 for(let i=0;i<3;i++)limitAction('test','bounded',3);
 assert.throws(()=>limitAction('test','bounded',3),{code:'RATE_LIMITED'});
 const cross=new Request('http://localhost/api/games',{method:'POST',headers:{cookie:cookies.a,'sec-fetch-site':'cross-site'},body:JSON.stringify(body())});assert.equal((await create(cross)).status,403);
 console.log('OK: five-game atomic cap (create/join), authenticated private lists, resume, expiry, code/guest entry, no name/ID spoofing, admin roles, secure password reset, body bounds, CSRF and shared rate limits');
}
void run().catch(error=>{console.error(error);process.exitCode=1});
