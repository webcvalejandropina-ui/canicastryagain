import assert from 'node:assert/strict';
import Database from 'better-sqlite3';
import { runMigrations } from '../src/backend/shared/infrastructure/db/migrations';
import { playerProfileSchema } from '../src/features/session/profile';
assert.deepEqual(playerProfileSchema.parse({}),{});
assert.deepEqual(playerProfileSchema.parse({age:28,locality:'  Pamplona  '}),{age:28,locality:'Pamplona'});
for(const age of [-1,121,18.5,'28',null,Infinity])assert(!playerProfileSchema.safeParse({age}).success);
assert(!playerProfileSchema.safeParse({locality:'a'.repeat(81)}).success);
const db=new Database(':memory:');
db.exec('CREATE TABLE players(id TEXT PRIMARY KEY,alias TEXT NOT NULL,password_hash TEXT NOT NULL,created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP)');
db.prepare('INSERT INTO players(id,alias,password_hash) VALUES(?,?,?)').run('old','Anterior','hash');
runMigrations(db);
assert.deepEqual(db.prepare('SELECT age,locality FROM players WHERE id=?').get('old'),{age:null,locality:null});
assert.throws(()=>db.prepare('UPDATE players SET age=? WHERE id=?').run(121,'old'));
const text="Villa '); DROP TABLE players; --";
db.prepare('UPDATE players SET age=?,locality=? WHERE id=?').run(28,text,'old');
assert.equal((db.prepare('SELECT locality FROM players WHERE id=?').get('old') as {locality:string}).locality,text);
runMigrations(db);
assert.equal((db.prepare('SELECT count(*) AS n FROM players').get() as {n:number}).n,1);
db.close();
console.log('Profile: optional fields, age limits, locality, migration and parameter safety OK');
